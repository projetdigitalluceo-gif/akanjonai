(function () {
  const textEls = document.querySelectorAll('[data-i18n]');
  const htmlEls = document.querySelectorAll('[data-i18n-html]');

  // Capture the French baseline straight from the DOM (single source of truth)
  textEls.forEach(el => { if (el.dataset.fr === undefined) el.dataset.fr = el.textContent; });
  htmlEls.forEach(el => { if (el.dataset.frHtml === undefined) el.dataset.frHtml = el.innerHTML; });

  function apply(lang) {
    const d = DICT[lang]; // undefined for 'fr' → fall back to baseline
    textEls.forEach(el => {
      const k = el.getAttribute('data-i18n');
      el.textContent = (d && d[k] != null) ? d[k] : el.dataset.fr;
    });
    htmlEls.forEach(el => {
      const k = el.getAttribute('data-i18n-html');
      el.innerHTML = (d && d[k] != null) ? d[k] : el.dataset.frHtml;
    });
    const meta = META[lang] || META.fr;
    document.documentElement.lang = lang;
    document.title = meta.title;
    const md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', meta.desc);
    document.querySelectorAll('.lang-btn').forEach(b => {
      const on = b.dataset.lang === lang;
      b.classList.toggle('active', on);
      b.setAttribute('aria-pressed', String(on));
    });
  }

  const SUPPORTED = ['fr', 'en', 'mg'];
  let saved = null;
  try { saved = localStorage.getItem('akanjonai-lang'); } catch (e) {}
  let initial = saved && SUPPORTED.indexOf(saved) !== -1 ? saved : null;
  if (!initial) {
    const nav = (navigator.language || 'fr').toLowerCase();
    initial = nav.indexOf('mg') === 0 ? 'mg' : (nav.indexOf('en') === 0 ? 'en' : 'fr');
  }
  apply(initial);

  document.addEventListener('click', e => {
    const btn = e.target.closest('.lang-btn');
    if (!btn) return;
    const lang = btn.dataset.lang;
    try { localStorage.setItem('akanjonai-lang', lang); } catch (e) {}
    apply(lang);
  });
})();
